/**
 * Hand-authored landmarks for the 43 illustrations used by SLAY.
 * Coordinates are UVs in the original image, with (0, 0) at its upper left.
 * Ellipses deliberately stay inside subjects: arena ropes, boots on the mat,
 * corner posts, crowds and the card frame should remain pinned.
 *
 * These are a custom 2D deformation rig, not Live2D Cubism model data.
 * Every source was inspected individually with view_image on 2026-10-04.
 * Closed, obscured, profile and very small eyes are intentionally omitted.
 */

const part = (motion, center, radius, amount, twist = 0, phase = 0) => ({
  center,
  radius,
  motion,
  amount,
  ...(twist ? { twist } : {}),
  ...(phase ? { phase } : {}),
});

const eye = (center, radius, skin) => ({ center, radius, skin });

// Each tuple contains its own measured center and radius; only amplitudes and
// timing are shared. Extra hair/limb regions never reuse the standing pose UVs.
const fighter = ({
  head,
  torso,
  hair,
  arms = [],
  eyes = [],
  intensity = 1,
}) => ({
  kind: "fighter",
  parts: [
    part("breath", torso[0], torso[1], [0.0008, 0.0027 * intensity]),
    part("head", head[0], head[1], [0.0028, 0.0035 * intensity], 0.008),
    ...hair.map(([center, radius], index) =>
      part("hair", center, radius, [0.0047, 0.0028], 0.012, 0.65 + index * 1.2),
    ),
    ...arms.map(([center, radius], index) =>
      part("arm", center, radius, [0.0017, 0.0022], 0.006, 1.6 + index * 1.3),
    ),
  ],
  eyes,
});

// Cards use smaller motion because their characters touch one another and
// share the texture with a static arena. A subject can be upside down or lying
// down; its UVs always describe that source instead of a canonical body shape.
const subject = (head, torso, hair, phase = 0) => [
  part("breath", torso[0], torso[1], [0.0006, 0.0018], 0, phase),
  part("head", head[0], head[1], [0.0017, 0.0023], 0.005, phase + 0.4),
  part("hair", hair[0], hair[1], [0.003, 0.0018], 0.007, phase + 0.9),
];

const card = (parts, eyes = []) => ({ kind: "card", parts, eyes });

